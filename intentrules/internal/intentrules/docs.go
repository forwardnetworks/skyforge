package intentrules

import (
	"fmt"
	"sort"
	"strings"

	"github.com/forwardnetworks/skyforge/intentrules/internal/netlabref"
)

type docRow struct{ id, code, class, kind, text string }

// RenderDocs renders the rules page from the loaded model, so the page cannot disagree with what runs. A gate regenerates it and
// fails on a difference.
func RenderDocs(e *Engine) string {
	var b strings.Builder
	b.WriteString("# Design-time intent rules\n\n")
	b.WriteString("Generated by `go run ./cmd/intentrules docs` from `internal/intentrules/`. Do not edit by hand; a check fails when this page differs from the model.\n\n")
	b.WriteString("The model is written in Infrahub's schema language (`schema/`, stock Infrahub YAML); what Skyforge adds lives in `sidecar/`. A Go evaluator ")
	b.WriteString("reads a netlab topology before any compile, builds the objects the schema describes (with netlab's defaults filled in) and reports findings in the ")
	b.WriteString("same shape as the compile's (`internal/netlabref`), with `source: intentrules`. netlab's own result wins: a code the compile already reported is not repeated.\n\n")

	var rows []docRow
	for _, r := range e.Rules {
		class, _, _, _, _ := e.textFor(r.Code, r.Class)
		rows = append(rows, docRow{r.ID, r.Code, class, r.Kind, oneLine(r.Description)})
	}
	rows = append(rows, e.constraintRows()...)
	sort.SliceStable(rows, func(i, j int) bool { return rows[i].id < rows[j].id })

	b.WriteString("## Rules\n\n")
	b.WriteString("| Rule | Code | Class | Kind | What it finds |\n|---|---|---|---|---|\n")
	for _, r := range rows {
		fmt.Fprintf(&b, "| `%s` | `%s` | %s | %s | %s |\n", r.id, r.code, r.class, r.kind, r.text)
	}

	b.WriteString("\n## Who owns each code\n\n")
	b.WriteString("| Code | Class | Owner of the text |\n|---|---|---|\n")
	codes := map[string]bool{}
	for _, r := range rows {
		codes[r.code] = true
	}
	for _, c := range sortedKeys(codes) {
		owner := "this layer (sidecar)"
		if _, _, _, ok := netlabref.RuleText(c); ok {
			owner = "netlab's classifier (`netlabref`); the compile's finding wins"
		}
		class, _, _, _, _ := e.textFor(c, "")
		fmt.Fprintf(&b, "| `%s` | %s | %s |\n", c, class, owner)
	}

	b.WriteString("\n## Model\n\n")
	for _, name := range e.Schema.Order {
		k := e.Schema.Kinds[name]
		kind := "node"
		if k.Generic {
			kind = "generic"
		}
		fmt.Fprintf(&b, "### %s (%s)\n\n%s\n\n", name, kind, k.Description)
		if len(k.InheritFrom) > 0 {
			fmt.Fprintf(&b, "Inherits: %s\n\n", strings.Join(k.InheritFrom, ", "))
		}
		if len(k.Attributes) > 0 {
			b.WriteString("| Attribute | Type | Required | netlab key |\n|---|---|---|---|\n")
			for _, a := range k.Attributes {
				req := "yes"
				if a.Optional || a.HasDefault {
					req = "no"
				}
				fmt.Fprintf(&b, "| `%s` | %s | %s | %s |\n", a.Name, a.Kind, req, e.netlabKey(name, a.Name))
			}
			b.WriteString("\n")
		}
		if len(k.Relationships) > 0 {
			b.WriteString("| Relationship | Peer | Cardinality | Min | Max | Required |\n|---|---|---|---|---|---|\n")
			for _, r := range k.Relationships {
				req := "no"
				if !r.Optional {
					req = "yes"
				}
				fmt.Fprintf(&b, "| `%s` | %s | %s | %d | %d | %s |\n", r.Name, r.Peer, r.Cardinality, r.MinCount, r.MaxCount, req)
			}
			b.WriteString("\n")
		}
		for _, u := range k.Uniqueness {
			fmt.Fprintf(&b, "Unique: `%s` (scope %s)\n\n", strings.Join(u.Elements, ", "), u.Scope)
		}
	}
	return b.String()
}

func oneLine(s string) string { return strings.Join(strings.Fields(s), " ") }

func (e *Engine) netlabKey(kind, member string) string {
	if a := e.annotationFor(kind, member); a != nil {
		if k, ok := a.Netlab["key"]; ok {
			return fmt.Sprintf("`%v`", k)
		}
	}
	return ""
}

// constraintRows lists the schema constraints that map to a finding code, as rows of the rules table.
func (e *Engine) constraintRows() []docRow {
	var out []docRow
	for _, key := range sortedKeys(e.Sidecar.Annotations) {
		a := e.Sidecar.Annotations[key]
		if a == nil {
			continue
		}
		kind, member, _ := strings.Cut(key, ".")
		for _, c := range sortedKeys(a.Findings) {
			code := a.Findings[c]
			class, _, _, _, _ := e.textFor(code, "")
			out = append(out, docRow{"constraint:" + key + ":" + c, code, class, kind,
				fmt.Sprintf("schema constraint `%s` on `%s`: %s", c, member, strings.TrimSpace(a.Messages[c]))})
		}
	}
	return out
}
